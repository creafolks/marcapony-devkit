import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Capability } from './api.js'

/**
 * AGENTS.md generation. `marcapony app link` fetches the scope-filtered
 * capability catalog and writes it here so the project's AI coding assistant
 * has the exact SDK call + input/response shape for only the features this app
 * can use. The block is delimited by markers and regenerated on every link;
 * anything outside the markers is left untouched.
 */

const AGENTS_FILE = 'AGENTS.md'
const SDK_PACKAGE = 'marcapony-sdk'

export const AGENTS_BEGIN =
  '<!-- marcapony:begin (generated by `marcapony app link`; regenerated each link — edit outside this block) -->'
export const AGENTS_END = '<!-- marcapony:end -->'

export interface RenderAgentsOptions {
  appName: string
  capabilities: Capability[]
}

export function renderAgents({ appName, capabilities }: RenderAgentsOptions): string {
  const lines: string[] = [
    AGENTS_BEGIN,
    '',
    `# Marcapony integration — ${appName}`,
    '',
    'This project uses Marcapony (a hosted backend) through the Marcapony SDK.',
    '',
    '## Rules',
    `- Install the SDK if the project does not depend on it yet: \`npm install ${SDK_PACKAGE}\` (public npm, no auth needed).`,
    '- The API key is in `.dev.vars` as `MARCAPONY_API_KEY`. Never commit it and never expose it to the client — use it only in server-side code.',
    '- Create the client on the server, passing BOTH values — without `baseUrl` the SDK defaults to production and ignores the URL that was written for you:',
    '  ```ts',
    `  import { createClient } from '${SDK_PACKAGE}'`,
    '  const mp = createClient({',
    '    apiKey: env.MARCAPONY_API_KEY, // env on Workers, process.env in Node',
    '    baseUrl: env.MARCAPONY_API_URL,',
    '    appId: env.MARCAPONY_APP_ID, // set at deploy; needed by identity()',
    '  })',
    '  ```',
    '- Pass an `idempotencyKey` to every create call. Derive it once per logical write and reuse it across retries — a fresh value per attempt defeats the mechanism.',
    "- Writes may be simulated. An app starts in **test mode**, where Marcapony answers a write without performing it: you get back the record it would have created, marked `simulated: true`, with a `test_`-prefixed id for creates. Reads are always real. Treat a simulated response as success — do not branch on the marker or retry because of it. Test mode is switched off from the app's page in the Marcapony dashboard, and from that point the same calls create real records.",
    '- There are no delete operations on this surface. Once test mode is off, anything a write creates can only be removed from the Marcapony dashboard — so put writes behind an explicit user action rather than running them on page load.',
    '- An empty list is a valid answer. A new account has no products, customers or submissions yet; do not treat that as a failure or build an interface that assumes data exists.',
    "- Anything shown to a signed-in visitor (portal apps) must use `mp.forRequest(request)` and its `me.*` calls, never the account-wide client: the account-wide key returns every customer's records. Read who is signed in with `identity(request)` from the SDK (display and hiding buttons only; the platform enforces access). Never read, parse or forward the portal session cookie or the `x-marcapony-identity` header yourself, and never log it.",
    '- Every app has a data access mode (`dataAccess` in `marcapony.json`, set in the dashboard). Unless it is `account`, the plain client cannot read customers, reservations, orders, payment links or form entries: those calls answer 403 `identity_required`. It can still read the catalog and book or send a form for an anonymous visitor. Do not try to work around this; customer data goes through `mp.forRequest(request)`. A deploy can only narrow the mode, never widen it.',
    '- Create `mp.forRequest(request)` per request and never keep it, or anything it returned, in module scope or a global cache: one worker serves many visitors, and a cached answer would be shown to the next one.',
    "- A team tool (opened by a team member from the dashboard) gets an identity with `kind: 'member'`. Make its calls through `mp.forRequest(request).reservations`, `.orders` and `.customers` so the member's own role limits them; `me.*` is for customers only. When `identity(request).preview` is true, writes are simulated: show a banner instead of claiming the change was saved.",
    '- Deploy with `npx marcapony app deploy`. Never run wrangler or git deploy commands.',
    '',
    '## Available operations',
    '',
  ]

  if (capabilities.length === 0) {
    lines.push(
      '_No operations are listed — this key has no scopes, or the catalog could not be fetched. Re-run `marcapony app link` in this project._',
    )
  } else {
    lines.push(
      "Only the operations this app's key can use are listed. Wire up only what this project needs.",
      '',
    )
    for (const cap of capabilities) {
      const plugin = cap.requiresPlugin ? ` · requires the \`${cap.requiresPlugin}\` plugin` : ''
      lines.push(
        `### ${cap.id} — ${cap.summary}`,
        `\`${cap.method} ${cap.path}\` · scope \`${cap.scope}\`${plugin}`,
        '```ts',
        cap.sdk,
        '```',
      )
      if (cap.input) lines.push(`- Input: \`${cap.input}\``)
      lines.push(`- Returns: \`${cap.response}\``)
      for (const note of cap.notes) lines.push(`- ${note}`)
      lines.push('')
    }
  }

  lines.push(AGENTS_END)
  return lines.join('\n')
}

/**
 * Replace the marcapony block in-place when present, otherwise append it —
 * preserving any hand-written or other-tool content in the file.
 */
export function upsertAgentsBlock(existing: string, block: string): string {
  const begin = existing.indexOf(AGENTS_BEGIN)
  const end = existing.indexOf(AGENTS_END)
  if (begin !== -1 && end !== -1 && end > begin) {
    return `${existing.slice(0, begin)}${block}${existing.slice(end + AGENTS_END.length)}`
  }
  if (existing.trim().length === 0) return `${block}\n`
  return `${existing.replace(/\n+$/, '')}\n\n${block}\n`
}

export function writeAgentsFile(cwd: string, block: string): void {
  const path = join(cwd, AGENTS_FILE)
  const existing = existsSync(path) ? readFileSync(path, 'utf8') : ''
  writeFileSync(path, upsertAgentsBlock(existing, block))
}

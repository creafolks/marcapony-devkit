import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Capability } from './api.js'

/**
 * AGENTS.md generation. `marcapony app link` fetches the scope-filtered
 * capability catalog and writes it here so the project's AI coding assistant
 * has the exact SDK call + input/response shape for only the features this app
 * can use. The block is delimited by markers and regenerated on every link;
 * anything outside the markers is left untouched.
 */

const AGENTS_FILE = 'AGENTS.md'
const SDK_PACKAGE = 'marcapony-sdk'

export const AGENTS_BEGIN =
  '<!-- marcapony:begin (generated by `marcapony app link`; regenerated each link — edit outside this block) -->'
export const AGENTS_END = '<!-- marcapony:end -->'

export interface RenderAgentsOptions {
  appName: string
  capabilities: Capability[]
  /** The local file `link` wrote the key into. */
  envFile?: string
}

export function renderAgents({
  appName,
  capabilities,
  envFile = '.env.local',
}: RenderAgentsOptions): string {
  const lines: string[] = [
    AGENTS_BEGIN,
    '',
    `# Marcapony integration — ${appName}`,
    '',
    'This project uses Marcapony (a hosted backend) through the Marcapony SDK.',
    '',
    '## Rules',
    `- Install the SDK if the project does not depend on it yet: \`npm install ${SDK_PACKAGE}\` (public npm, no auth needed).`,
    `- The API key is in \`${envFile}\` as \`MARCAPONY_API_KEY\`. Never commit it and never expose it to the client — use it only in server-side code.`,
    '- Create the client on the server, passing BOTH values — without `baseUrl` the SDK defaults to production and ignores the URL that was written for you:',
    '  ```ts',
    `  import { createClient } from '${SDK_PACKAGE}'`,
    '  const mp = createClient({',
    '    apiKey: env.MARCAPONY_API_KEY, // the `env` your fetch handler receives',
    '    baseUrl: env.MARCAPONY_API_URL,',
    '    appId: env.MARCAPONY_APP_ID, // set at deploy; needed by identity()',
    '  })',
    '  ```',
    '- Pass an `idempotencyKey` to every create call. Derive it once per logical write and reuse it across retries — a fresh value per attempt defeats the mechanism.',
    "- Writes may be simulated. An app starts in **test mode**, where Marcapony answers a write without performing it: you get back the record it would have created, marked `simulated: true`, with a `test_`-prefixed id for creates. Reads are always real. Treat a simulated response as success — do not branch on the marker or retry because of it. Test mode is switched off from the app's page in the Marcapony dashboard, and from that point the same calls create real records.",
    '- Almost nothing on this surface can be deleted (the exceptions are listed under the operations below). Once test mode is off, anything else a write creates can only be removed from the Marcapony dashboard — so put writes behind an explicit user action rather than running them on page load.',
    "- A customer app in the portal can keep its own data per signed-in customer: declare `collections` in `marcapony.json` (`name`, `read: 'own'`, `write: 'own'`, optional `maxRows` and up to 4 `indexes` of `{ field, type }`), add a permission to `permissions` whose `grants` are `records.own.read` and `records.own.write` (reads need the first, writes the second), deploy, then use `mp.forRequest(request).me.records('name')` with `get`, `list`, `put`, `create` and `delete`. The owner must give that permission to customers on the app's page in the dashboard; until then every records call answers 403, so tell them. A list filters and orders only by a declared index, one per query. These writes are real in test mode, and each environment has its own records. Do not store payment card data, passwords or anything the platform already holds (reservations, orders, profile).",
    "- Data that belongs to the app rather than one customer (a price list, today's menu, a schedule) goes in a shared collection: `{ name, scope: 'shared', read: 'public' | 'signed_in', write: [writers] }`, where the writers are `feed` (an automation fills it), `team` (members of a team app, grant `records.shared.team.write`) and `server` (this app's key with no signed-in person). Read and write it with `mp.records('name')`, or `mp.forRequest(request).records('name')` for a `signed_in` collection or a team write. `signed_in` reads need a permission with `records.shared.read` (customers) or `records.shared.team.read` (members), which the owner gives out like `records.own.*`, or every read answers 403; `public` reads need no grant and can be up to a minute old. Customers never write a shared collection, and every reader of the app can see it, so never put personal data in one.",
    "- A marketplace app lets customers the owner made sellers list their own products: add a permission whose `grants` are `products.own.read` and `products.own.write`, deploy, then use `mp.forRequest(request).me.products` (`list`, `get`, `create`, `update`, `setVariants`, `submit`, `unpublish`, `delete`) and `me.media.upload(bytes, { contentType })` for images, whose ids go in `imageIds`. Products start as drafts; `submit` sends one to the owner's team, which approves it before it goes live (unless the owner turned review off), and an edit of a live product waits in `pendingChanges` while the old version keeps selling. Show the seller `reviewStatus` and `reviewNote`. The owner can give these grants only to a portal role on the app's page in the dashboard (a seller role they assign), and the account's package must include the marketplace; until both are true every write answers 403, so tell them. Status, slug, tags and language cannot be set by a seller. In test mode (where new apps start) product writes are simulated and return an id that does not exist, so a follow-up call on it answers 404; image uploads are real. Do not read that 404 as a bug.",
    '- An empty list is a valid answer. A new account has no products, customers or submissions yet; do not treat that as a failure or build an interface that assumes data exists.',
    "- A portal app is shown inside the customer portal, full width under the portal's header and with no frame around it. Make it look like part of the portal: do not wrap the whole screen in a card, border or shadow, start with a heading and the content, and keep cards for groups inside. The portal sends its theme to the app (`{ type: 'mp:theme', theme: { appearance, colors, radius, fontFamily } }`, colours as `rgb(r g b)`) after load, when the app posts `{ type: 'mp:ready' }` to `window.parent`, and whenever the visitor switches light and dark. Apply it to CSS variables and style only with those variables, never fixed colours, or the app turns unreadable in dark mode. Read the message only when `event.source === window.parent` and validate every value before it reaches a style. Apps made with `create-marcapony-app` already do this in `src/ui/portal-theme.ts`.",
    "- Anything shown to a signed-in visitor (portal apps) must use `mp.forRequest(request)` and its `me.*` calls, never the account-wide client: the account-wide key returns every customer's records. Read who is signed in with `identity(request)` from the SDK (display and hiding buttons only; the platform enforces access). Never read, parse or forward the portal session cookie or the `x-marcapony-identity` header yourself, and never log it.",
    '- Every app has a data access mode (`dataAccess` in `marcapony.json`, set in the dashboard). Unless it is `account`, the plain client cannot read customers, reservations, orders, payment links or form entries: those calls answer 403 `identity_required`. It can still read the catalog and book or send a form for an anonymous visitor. Do not try to work around this; customer data goes through `mp.forRequest(request)`. A deploy can only narrow the mode, never widen it.',
    '- Create `mp.forRequest(request)` per request and never keep it, or anything it returned, in module scope or a global cache: one server instance serves many visitors, and a cached answer would be shown to the next one.',
    "- A team tool (opened by a team member from the dashboard) gets an identity with `kind: 'member'`. Make its calls through `mp.forRequest(request).reservations`, `.orders` and `.customers` so the member's own role limits them; `me.*` is for customers only. When `identity(request).preview` is true, writes are simulated: show a banner instead of claiming the change was saved.",
    '- Deploy only with `npx marcapony app deploy`. No other deploy tool applies to this project. Before deploying in a project others also work on, run `npx marcapony app pull`; a deploy stops with exit code 2 when someone deployed after your last sync.',
    '- Settings and secrets the app needs go in `env` in `marcapony.json` and are set with `npx marcapony app env set NAME` (never in the code). The app reads them from the `env` its fetch handler receives.',
    '- The app runs in the Marcapony runtime: a standard fetch handler, no file system at request time, limited CPU time per request. Prefer web APIs (fetch, Request, Response, crypto) over Node built-ins.',
    '',
    '## Available operations',
    '',
  ]

  if (capabilities.length === 0) {
    lines.push(
      '_No operations are listed — this key has no scopes, or the catalog could not be fetched. Re-run `marcapony app link` in this project._',
    )
  } else {
    lines.push(
      "Only the operations this app's key can use are listed. Wire up only what this project needs.",
      '',
    )
    for (const cap of capabilities) {
      const plugin = cap.requiresPlugin ? ` · requires the \`${cap.requiresPlugin}\` plugin` : ''
      lines.push(
        `### ${cap.id} — ${cap.summary}`,
        `\`${cap.method} ${cap.path}\` · scope \`${cap.scope}\`${plugin}`,
        '```ts',
        cap.sdk,
        '```',
      )
      if (cap.input) lines.push(`- Input: \`${cap.input}\``)
      lines.push(`- Returns: \`${cap.response}\``)
      for (const note of cap.notes) lines.push(`- ${note}`)
      lines.push('')
    }
  }

  lines.push(AGENTS_END)
  return lines.join('\n')
}

/**
 * Replace the marcapony block in-place when present, otherwise append it —
 * preserving any hand-written or other-tool content in the file.
 */
export function upsertAgentsBlock(existing: string, block: string): string {
  const begin = existing.indexOf(AGENTS_BEGIN)
  const end = existing.indexOf(AGENTS_END)
  if (begin !== -1 && end !== -1 && end > begin) {
    return `${existing.slice(0, begin)}${block}${existing.slice(end + AGENTS_END.length)}`
  }
  if (existing.trim().length === 0) return `${block}\n`
  return `${existing.replace(/\n+$/, '')}\n\n${block}\n`
}

export function writeAgentsFile(cwd: string, block: string): void {
  const path = join(cwd, AGENTS_FILE)
  const existing = existsSync(path) ? readFileSync(path, 'utf8') : ''
  writeFileSync(path, upsertAgentsBlock(existing, block))
}
